def apply(pairs, text, tag):
    for i, (a, b) in enumerate(pairs, 1):
        n = text.count(a)
        if n != 1:
            print('  [FAIL] %s #%d 计数=%d  :: %s' % (tag, i, n, a[:60].replace('\n', '⏎')))
            continue
        text = text.replace(a, b)
        print('  [ok]   %s #%d' % (tag, i))
    return text


